import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const load = async file => (await import('data:text/javascript;base64,' + Buffer.from(await readFile(file, 'utf8')).toString('base64'))).default;
const response = () => ({ code: 200, headers: {}, data: null, setHeader(k,v){this.headers[k]=v;}, status(n){this.code=n;return this;}, json(v){this.data=v;return this;} });
const auth = await load('api/auth-status.js');
let res = response();
await auth({method:'GET',headers:{}}, res);
assert.equal(res.code, 401);
assert.equal(res.data.authenticated, false);
let called = false;
const originalFetch = globalThis.fetch;
globalThis.fetch = async () => {called=true;return {ok:false,status:401};};
res = response();
await auth({method:'GET',headers:{authorization:'Bearer forged-token'}}, res);
assert.equal(called,true);assert.equal(res.code,401);
globalThis.fetch = async () => ({ok:true,json:async()=>({id:'test-user',email:'private@example.invalid'})});
res=response();await auth({method:'GET',headers:{authorization:'Bearer test-token'}},res);
assert.deepEqual(res.data,{authenticated:true,userId:'test-user',isBetaTester:false});
globalThis.fetch = originalFetch;
const checkout = await load('api/create-checkout.js');
res=response();await checkout({method:'POST'},res);assert.equal(res.code,503);
res=response();await checkout({method:'GET'},res);assert.equal(res.code,405);assert.equal(res.headers.Allow,'POST');
console.log('ReconFeed API contracts passed: authenticated status, private fields, fail-closed checkout.');
