import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import {createRequire} from 'node:module';
import vm from 'node:vm';
const ts=createRequire(new URL('../mobile/package.json',import.meta.url))('typescript');
const src=await readFile(new URL('../mobile/feedEventQueue.ts',import.meta.url),'utf8');
const js=ts.transpileModule(src,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText;
const module={exports:{}};
vm.runInNewContext(js,{module,exports:module.exports,Promise,JSON,Math,Array,Number,String,Set,console});
const {createFeedEventQueue}=module.exports;
const items=new Map();
const store={async getItem(k){return items.get(k)||null},async setItem(k,v){items.set(k,v)},async removeItem(k){items.delete(k)}};
const sent=[];
let failed=true;
const insert=async rows=>{
 if(failed){failed=false;return {error:{message:'Temporary network error'}}}
 sent.push(...rows);return {error:null};
};
const queue=createFeedEventQueue({userId:'account-A',storage:store,insert});
await queue.hydrate();
queue.enqueue('post-1','watch',24500,25000);
queue.enqueue('post-2','not_interested');
assert.equal(queue.size(),2);
assert.equal(await queue.flush(),false,'Transient failure should retain events');
assert.equal(queue.size(),2);
assert.equal(await queue.flush(),true,'Retry should submit the same batch');
assert.equal(queue.size(),0);
assert.deepEqual(sent.map(x=>x.event_type),['watch','not_interested']);
queue.enqueue('post-3','share');
await new Promise(r=>setTimeout(r,10));
queue.dispose();
const recovered=createFeedEventQueue({userId:'account-A',storage:store,insert});
await recovered.hydrate();
assert.equal(recovered.size(),1,'Offline events should survive restart for same account');
await recovered.flush();
assert.equal(sent.length,3);
assert.equal((await store.getItem('reconfeed_feed_queue_v1_account-A')),null);
const different=createFeedEventQueue({userId:'account-B',storage:store,insert});
await different.hydrate();
assert.equal(different.size(),0,'Other users cannot see prior account events');
different.enqueue('post-4','watch',800000000,900000000);
assert.equal(different.size(),1);
await different.clear();
assert.equal(different.size(),0,'Privacy reset must erase pending events');
const bounded=createFeedEventQueue({userId:'account-C',storage:store,insert});
await bounded.hydrate();
for(let i=0;i<125;i++)bounded.enqueue('p'+i,'watch',i,1000);
assert.equal(bounded.size(),100,'Queue must never grow unbounded');
await bounded.clear();
console.log('ReconFeed batched telemetry passed: retries, per-account isolation, persistence, bounds, clearing.');
